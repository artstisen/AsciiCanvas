namespace AsciiCanvas;

/// <summary>A mouse button.</summary>
public enum MouseButton
{
    /// <summary>No button (for example a move or wheel event).</summary>
    None = 0,

    /// <summary>The primary button.</summary>
    Left,

    /// <summary>The middle button or wheel click.</summary>
    Middle,

    /// <summary>The secondary button.</summary>
    Right,
}
